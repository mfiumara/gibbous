import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { DatabaseSync } from 'node:sqlite';
import type { Thread } from './store.ts';
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'gibbous-human-'));
process.env.GIBBOUS_HOME = home; process.env.HERMES_HOME = home;
const { state, migrate, saveNow } = await import('./store.ts');
const openCount = (ts: any[]) => ts.reduce((n, x) => n + humanTasks(x).filter((y: any) => y.doneAt == null).length, 0);
const { unreadCount, openHumanTask, humanTasks, addHumanTasks, patchHumanTask, removeHumanTask, completeHumanTask, taskNotifier, threadForSession } = await import('./humanTasks.ts');
const { authorized, rpc, resolveThread, handleMcp } = await import('./mcp.ts');
const make = (id = 'thread', sessionId = 'session'): Thread => ({ id, sessionId, title: 'Device check', cwd: home, role: 'chat', status: 'idle', createdAt: 1, updatedAt: 1 });
test('legacy migration, stable ids, multi-task CRUD and badge count', () => {
  const legacy = { ...make(), humanTask: { text: 'Plug in.', at: 10, by: 'user' as const } };
  const t = migrate({ threads: [legacy] }).threads[0];
  assert.equal(humanTasks(t)[0].id, 'legacy-10');
  const direct = { ...legacy }; patchHumanTask(direct, 'legacy-10', { done: true }, 15);
  assert.equal(humanTasks(direct)[0].doneAt, 15); assert.equal(direct.humanTask, undefined);
  assert.deepEqual(humanTasks({ ...legacy, humanTasks: [] }), []);
  assert.equal(humanTasks(migrate({ threads: [t] }).threads[0]).length, 1);
  const [a, b] = addHumanTasks(t, ['Approve.', 'Decide.'], 'agent', 20);
  assert.equal(openCount([t, make('other')]), 3);
  patchHumanTask(t, a.id, { text: 'Approve purchase.', done: true }, 30);
  patchHumanTask(t, a.id, { done: true }, 40); assert.equal(a.doneAt, 30);
  assert.equal(openCount([t]), 2);
  patchHumanTask(t, a.id, { done: false }); assert.equal(a.doneAt, undefined);
  completeHumanTask(t, { text: b.text }); removeHumanTask(t, a.id);
  assert.equal(openHumanTask(t), true); assert.equal(humanTasks(t).length, 2);
  assert.throws(() => addHumanTasks(t, ['valid', ''], 'user')); assert.equal(humanTasks(t).length, 2);
  assert.throws(() => addHumanTasks(t, Array(11).fill('x'), 'user'));
  assert.throws(() => patchHumanTask(t, 'missing', { done: true }));
  state.threads = [t]; saveNow();
  assert.deepEqual(migrate(JSON.parse(fs.readFileSync(path.join(home, 'state.json'), 'utf8'))).threads[0].humanTasks, t.humanTasks);
});
test('notification debounce combines per thread and drops completed items', async () => {
  const t = make(), other = make('other'); const sent: { id: string; texts: string[] }[] = [];
  const enqueue = taskNotifier((t, tasks) => sent.push({ id: t.id, texts: tasks.map(task => task.text) }), 20);
  const a = addHumanTasks(t, ['One', 'Two'], 'agent'); enqueue(t, a);
  enqueue(t, addHumanTasks(t, ['Three'], 'agent')); patchHumanTask(t, a[0].id, { done: true });
  enqueue(other, addHumanTasks(other, ['Separate'], 'agent'));
  for (let i = 0; i < 200 && sent.length < 2; i++) await new Promise(r => setTimeout(r, 10));
  assert.deepEqual(sent, [{ id: t.id, texts: ['Two', 'Three'] }, { id: other.id, texts: ['Separate'] }]);
});
test('session ancestry resolves continuations, rejects unknown/cycles and remote guesses', () => {
  const t = make();
  assert.equal(threadForSession([t], 'next', id => id === 'next' ? 'session' : undefined), t);
  assert.equal(threadForSession([t], 'next-again', id => ({ 'next-again': 'next', next: 'session' } as Record<string, string>)[id]), t);
  assert.equal(threadForSession([t], 'other', () => 'other'), undefined);
  assert.equal(threadForSession([{ ...t, host: 'remote' }], 'session', () => undefined), undefined);
  state.threads = [t];
  const db = new DatabaseSync(path.join(home, 'state.db'));
  db.exec('CREATE TABLE sessions (id TEXT, parent_session_id TEXT); INSERT INTO sessions VALUES (\'continued\', \'session\');'); db.close();
  assert.equal(resolveThread('continued'), t); assert.equal(resolveThread('thread'), t); assert.equal(resolveThread('session'), t);
  assert.throws(() => resolveThread(undefined)); assert.throws(() => resolveThread('unknown'));
});
test('MCP JSON-RPC tools/list, call, done, invalid text, unknown tool/thread', async () => {
  state.threads = [make()];
  const call = async (method: string, params?: unknown): Promise<any> => rpc({ jsonrpc: '2.0', id: 1, method, params }, (t, action) => 'tasks' in action ? addHumanTasks(t, action.tasks, 'agent').map(t => t.id) : completeHumanTask(t, action));
  assert.equal((await call('tools/list')).result.tools.length, 3);
  assert.match((await call('initialize')).result.instructions, /BEFORE ending/);
  const result = await call('tools/call', { name: 'gibbous_request_human_task', arguments: { thread: 'thread', tasks: ['Connect the device.', 'Approve the purchase.'] } });
  assert.equal(result.result.isError, undefined);
  const created = JSON.parse(result.result.content[0].text).created;
  assert.equal(created.length, 2); assert.equal(state.threads[0].humanTasks?.[0].by, 'agent');
  assert.equal((await call('tools/call', { name: 'gibbous_complete_human_task', arguments: { thread: 'thread' } })).result.isError, true);
  await call('tools/call', { name: 'gibbous_complete_human_task', arguments: { thread: 'thread', task_id: created[0] } });
  assert.equal(openCount(state.threads), 1);
  const list = await call('tools/call', { name: 'gibbous_list_human_tasks', arguments: { thread: 'thread' } });
  assert.equal(JSON.parse(list.result.content[0].text).tasks.length, 2);
  await call('tools/call', { name: 'gibbous_complete_human_task', arguments: { thread: 'thread', text: 'Approve the purchase.' } });
  assert.equal(openHumanTask(state.threads[0]), false);
  for (const args of [{ thread: 'unknown', text: 'Approve.' }, { text: 'Approve.' }, { thread: 'thread', text: '' }]) assert.equal((await call('tools/call', { name: 'gibbous_request_human_task', arguments: args })).result.isError, true);
  assert.equal((await call('tools/call', { name: 'unknown' })).error.code, -32602);
  assert.equal((await call('unknown')).error.code, -32601);
  assert.equal(await rpc({ jsonrpc: '2.0', method: 'notifications/initialized' }, () => {}), undefined);
});
test('MCP rejects bad auth before reading body or mutating', async () => {
  assert.equal(authorized('Bearer test', 'test'), true); assert.equal(authorized('Bearer wrong', 'test'), false);
  let status = 0, read = false;
  const res = { writeHead(n: number) { status = n; return this; }, end() {} };
  await handleMcp({ method: 'POST', headers: { authorization: 'Bearer wrong' } } as any, res as any, async () => { read = true; }, () => assert.fail());
  assert.equal(status, 401); assert.equal(read, false);
});

test('the badge counts unread threads only: newer activity than seenAt, not archived or running', () => {
  const t = (o: any) => ({ status: 'idle', createdAt: 1, updatedAt: 10, ...o });
  assert.equal(unreadCount([t({ seenAt: 5 }), t({ seenAt: 10 }), t({ seenAt: 5, status: 'archived' }), t({ seenAt: 5, status: 'running' }), t({})]), 2);
});
