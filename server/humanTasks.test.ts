import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { DatabaseSync } from 'node:sqlite';
import type { Thread } from './store.ts';
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'gibbous-human-'));
process.env.GIBBOUS_HOME = home; process.env.HERMES_HOME = home;
const { state, migrate, saveNow } = await import('./store.ts');
const { attentionCount, openHumanTask, setHumanTask, completeHumanTask, threadForSession } = await import('./humanTasks.ts');
const { authorized, rpc, resolveThread, handleMcp } = await import('./mcp.ts');
const make = (id = 'thread', sessionId = 'session'): Thread => ({ id, sessionId, title: 'Device check', cwd: home, role: 'chat', status: 'idle', createdAt: 1, updatedAt: 1 });
test('human task transitions, replacement, migration and badge count', () => {
  const t = make(); setHumanTask(t, '  Plug in the device.  ', 'user', 10);
  assert.equal(attentionCount(2, [t]), 3); assert.equal(openHumanTask(t), true);
  const migrated = migrate({ threads: [t], settings: {} });
  assert.deepEqual(migrated.threads[0].humanTask, t.humanTask);
  completeHumanTask(t, 20); completeHumanTask(t, 30);
  assert.equal(t.humanTask!.doneAt, 20); assert.equal(attentionCount(2, [t]), 2);
  state.threads = [t]; saveNow();
  assert.deepEqual(migrate(JSON.parse(fs.readFileSync(path.join(home, 'state.json'), 'utf8'))).threads[0].humanTask, t.humanTask);
  setHumanTask(t, 'Approve the purchase.', 'agent', 40);
  assert.equal(t.humanTask!.doneAt, undefined); assert.equal(t.humanTask!.by, 'agent');
  delete t.humanTask; assert.equal(attentionCount(0, [t]), 0);
  assert.throws(() => setHumanTask(t, '', 'user')); assert.throws(() => setHumanTask(t, 'x'.repeat(1001), 'user'));
  assert.equal(migrate({ threads: [make()] }).threads[0].humanTask, undefined);
});
test('session ancestry resolves continuations, rejects unknown/cycles and remote guesses', () => {
  const t = make();
  assert.equal(threadForSession([t], 'next', id => id === 'next' ? 'session' : undefined), t);
  assert.equal(threadForSession([t], 'next-again', id => ({ 'next-again': 'next', next: 'session' } as Record<string, string>)[id]), t);
  assert.equal(threadForSession([t], 'other', () => 'other'), undefined);
  assert.equal(threadForSession([{ ...t, host: 'remote' }], 'session', () => undefined), undefined);
  state.threads = [t];
  const db = new DatabaseSync(path.join(home, 'state.db'));
  db.exec('CREATE TABLE sessions (id TEXT, parent_session_id TEXT); INSERT INTO sessions VALUES (\'continued\', \'session\');'); db.close();
  assert.equal(resolveThread('continued'), t); assert.equal(resolveThread('thread'), t); assert.equal(resolveThread('session'), t);
  assert.throws(() => resolveThread(undefined)); assert.throws(() => resolveThread('unknown'));
});
test('MCP JSON-RPC tools/list, call, done, invalid text, unknown tool/thread', async () => {
  state.threads = [make()];
  const call = async (method: string, params?: unknown): Promise<any> => rpc({ jsonrpc: '2.0', id: 1, method, params }, (t, text) => text === undefined ? completeHumanTask(t) : setHumanTask(t, text, 'agent'));
  assert.equal((await call('tools/list')).result.tools.length, 2);
  assert.equal((await call('initialize')).result.capabilities.tools != null, true);
  assert.equal((await call('tools/call', { name: 'gibbous_request_human_task', arguments: { thread: 'thread', text: 'Connect the device.' } })).result.isError, undefined);
  assert.equal(state.threads[0].humanTask?.by, 'agent');
  assert.equal((await call('tools/call', { name: 'gibbous_complete_human_task', arguments: { thread: 'thread' } })).result.isError, undefined);
  assert.equal(openHumanTask(state.threads[0]), false);
  for (const args of [{ thread: 'unknown', text: 'Approve.' }, { text: 'Approve.' }, { thread: 'thread', text: '' }]) assert.equal((await call('tools/call', { name: 'gibbous_request_human_task', arguments: args })).result.isError, true);
  assert.equal((await call('tools/call', { name: 'unknown' })).error.code, -32602);
  assert.equal((await call('unknown')).error.code, -32601);
  assert.equal(await rpc({ jsonrpc: '2.0', method: 'notifications/initialized' }, () => {}), undefined);
});
test('MCP rejects bad auth before reading body or mutating', async () => {
  assert.equal(authorized('Bearer test', 'test'), true); assert.equal(authorized('Bearer wrong', 'test'), false);
  let status = 0, read = false;
  const res = { writeHead(n: number) { status = n; return this; }, end() {} };
  await handleMcp({ method: 'POST', headers: { authorization: 'Bearer wrong' } } as any, res as any, async () => { read = true; }, () => assert.fail());
  assert.equal(status, 401); assert.equal(read, false);
});
